import "server-only";

import fs from "node:fs/promises";
import path from "node:path";

import { getStore, type Store } from "@netlify/blobs";

/**
 * Key-value storage for admin-edited content and uploaded media.
 *
 * - On Netlify (functions at runtime): Netlify Blobs, credentials injected
 *   automatically.
 * - During `next build` on Netlify: Netlify Blobs using SITE_ID (provided by
 *   Netlify) and NETLIFY_BLOBS_TOKEN (a personal access token you set), so
 *   prerendered pages contain the latest admin edits. The build fails if the
 *   token is missing rather than silently publishing stale content.
 * - Locally: files under `.data/blobs/` (gitignored).
 */

export type StoreName = "content" | "media";

type Meta = Record<string, string>;

export interface BlobBackend {
  getJSON<T>(key: string): Promise<T | null>;
  setJSON(key: string, value: unknown): Promise<void>;
  getBinary(key: string): Promise<{ data: ArrayBuffer; meta: Meta } | null>;
  setBinary(key: string, data: ArrayBuffer, meta: Meta): Promise<void>;
  delete(key: string): Promise<void>;
}

class NetlifyBackend implements BlobBackend {
  constructor(private store: Store) {}
  async getJSON<T>(key: string) {
    return ((await this.store.get(key, { type: "json", consistency: "strong" })) ??
      null) as T | null;
  }
  async setJSON(key: string, value: unknown) {
    await this.store.setJSON(key, value);
  }
  async getBinary(key: string) {
    const res = await this.store.getWithMetadata(key, {
      type: "arrayBuffer",
      consistency: "strong",
    });
    return res ? { data: res.data, meta: res.metadata as Meta } : null;
  }
  async setBinary(key: string, data: ArrayBuffer, meta: Meta) {
    await this.store.set(key, data, { metadata: meta });
  }
  async delete(key: string) {
    await this.store.delete(key);
  }
}

const LOCAL_ROOT = path.join(process.cwd(), ".data", "blobs");

class FileBackend implements BlobBackend {
  constructor(private dir: string) {}
  private file(key: string) {
    // Keys are generated by the app; still refuse path traversal.
    const safe = key.replace(/\.\.+/g, "").replace(/^[/\\]+/, "");
    return path.join(this.dir, safe);
  }
  async getJSON<T>(key: string) {
    try {
      return JSON.parse(await fs.readFile(this.file(key), "utf8")) as T;
    } catch {
      return null;
    }
  }
  async setJSON(key: string, value: unknown) {
    const f = this.file(key);
    await fs.mkdir(path.dirname(f), { recursive: true });
    await fs.writeFile(f, JSON.stringify(value, null, 2));
  }
  async getBinary(key: string) {
    try {
      const [buf, meta] = await Promise.all([
        fs.readFile(this.file(key)),
        fs.readFile(`${this.file(key)}.meta.json`, "utf8"),
      ]);
      const data = buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength);
      return { data: data as ArrayBuffer, meta: JSON.parse(meta) as Meta };
    } catch {
      return null;
    }
  }
  async setBinary(key: string, data: ArrayBuffer, meta: Meta) {
    const f = this.file(key);
    await fs.mkdir(path.dirname(f), { recursive: true });
    await fs.writeFile(f, Buffer.from(data));
    await fs.writeFile(`${f}.meta.json`, JSON.stringify(meta));
  }
  async delete(key: string) {
    await fs.rm(this.file(key), { force: true });
    await fs.rm(`${this.file(key)}.meta.json`, { force: true });
  }
}

const backends = new Map<StoreName, BlobBackend>();

function createBackend(name: StoreName): BlobBackend {
  // 1. Netlify Functions / `netlify dev`: the Blobs context is injected.
  try {
    return new NetlifyBackend(getStore({ name, consistency: "strong" }));
  } catch {
    // No injected context — fall through.
  }

  // 2. `next build` on Netlify: credentials must be passed explicitly.
  const siteID = process.env.SITE_ID;
  const token = process.env.NETLIFY_BLOBS_TOKEN;
  if (siteID && token) {
    return new NetlifyBackend(
      getStore({ name, siteID, token, consistency: "strong" }),
    );
  }
  if (process.env.NETLIFY === "true") {
    throw new Error(
      "Netlify Blobs credentials are missing during the build. Set NETLIFY_BLOBS_TOKEN " +
        "(a Netlify personal access token) in the site's environment variables so " +
        "prerendered pages include admin edits. See docs/deploy-netlify.md.",
    );
  }

  // 3. Local development.
  return new FileBackend(path.join(LOCAL_ROOT, name));
}

export function blobs(name: StoreName): BlobBackend {
  let backend = backends.get(name);
  if (!backend) {
    backend = createBackend(name);
    backends.set(name, backend);
  }
  return backend;
}
